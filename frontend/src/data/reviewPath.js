/**
 * 为某个阶段生成 AI 出题的提示词。
 *
 * 用阶段名 + 模块清单 + 验收标准来约束模型，避免它把后面的章节混进来——
 * 阶段测验的意义就是「只考这一段」，考超纲了就没法判断过没过。
 *
 * @param {Object} stage reviewStages 中的一项
 * @param {number} count 题量，默认 10
 * @returns {string} 可直接交给 AI 出卷接口的提示词
 */
export function buildStagePrompt(stage, count = 10) {
  const topics = stage.items.map((item) => item.name).join('、')
  const criteria = stage.acceptance.length > 0
    ? `。本卷用于检验以下验收标准：${stage.acceptance.join('；')}`
    : ''

  return [
    `请出一份「${stage.tag} · ${stage.title}」的阶段测验。`,
    '要求：',
    `1. 共 ${count} 道客观题（单选/多选/判断），不要出简答题`,
    `2. 只考以下考点：${topics}`,
    '3. 难度为自学自测水平，不要涉及后续阶段的知识，不要超纲',
    `4. 每题都要给出解析${criteria}`,
    '5. 每道题都要带 topic 字段，值必须是上面考点里的一个，原样照抄，不要改写或自创'
  ].join('\n')
}
