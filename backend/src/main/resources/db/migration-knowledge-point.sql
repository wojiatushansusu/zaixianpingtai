-- -------------------------------------------
-- 复习路径诊断：题目增加知识点
-- -------------------------------------------
-- 新库由 schema.sql 直接建出该列，无需执行本脚本。
-- 已有的库执行一次。存量题目该列为空，诊断里会显示「未标注知识点」——
-- 这是刻意的：宁可承认不知道，也不要按章节名瞎猜。

ALTER TABLE `question`
    ADD COLUMN `knowledge_point` VARCHAR(64)
        COMMENT '知识点（对应复习路径的阶段模块名，AI 出卷时标注）'
        AFTER `difficulty`;
